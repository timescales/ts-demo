//! Turn collected JSONL results into `summary.md` and LaTeX tables.
//!
//! Every reported number comes from these files. Nothing is typed in by hand.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::Result;
use serde_json::Value;

fn load(dir: &Path, name: &str) -> Vec<Value> {
    let Ok(s) = std::fs::read_to_string(dir.join(format!("{name}.jsonl"))) else {
        return Vec::new();
    };
    s.lines()
        .filter_map(|l| serde_json::from_str::<Value>(l).ok())
        .filter(|v| v.get("error").is_none())
        .collect()
}

fn f(v: &Value, k: &str) -> f64 {
    v.get(k).and_then(Value::as_f64).unwrap_or(f64::NAN)
}

fn u(v: &Value, k: &str) -> u64 {
    v.get(k).and_then(Value::as_u64).unwrap_or(0)
}

/// Latest result per key, so re-runs replace earlier lines.
fn latest<F: Fn(&Value) -> bool>(rows: &[Value], filter: F) -> BTreeMap<u64, Value> {
    rows.iter()
        .filter(|v| filter(v))
        .map(|v| (u(v, "n"), v.clone()))
        .collect()
}

fn fmt_ms(x: f64) -> String {
    if x.is_nan() {
        "--".into()
    } else if x >= 10_000.0 {
        format!("{:.1} s", x / 1000.0)
    } else if x >= 100.0 {
        format!("{x:.0}")
    } else if x >= 1.0 {
        format!("{x:.1}")
    } else {
        format!("{x:.2}")
    }
}

fn fmt_n(n: u64) -> String {
    match n {
        n if n >= 1_000_000 && n % 1_000_000 == 0 => format!("{}M", n / 1_000_000),
        n if n >= 1_000 && n % 1_000 == 0 => format!("{}k", n / 1_000),
        n => n.to_string(),
    }
}

fn is_default_mpc(v: &Value) -> bool {
    v.get("circuit").and_then(Value::as_str) == Some("log")
        && v.get("authenticated").and_then(Value::as_bool) == Some(true)
        && u(v, "parties") == 3
        && u(v, "band_ticks") == 65
}

pub(crate) fn write(dir: &Path, tables: &Path) -> Result<()> {
    std::fs::create_dir_all(tables)?;
    let reference = latest(&load(dir, "reference"), |v| u(v, "band_ticks") == 65);
    let tee = latest(&load(dir, "tee"), |v| u(v, "band_ticks") == 65);
    let mpc_all = load(dir, "mpc");
    let mpc = latest(&mpc_all, is_default_mpc);
    let zk = latest(&load(dir, "zk"), |v| u(v, "band_ticks") == 65);
    let sort = latest(&load(dir, "sort"), |_| true);
    let sizes = load(dir, "sizes");
    let settlement = load(dir, "settlement");

    let mut md = String::from(
        "# Benchmark summary\n\nGenerated by `timescales-bench report` from `target/bench/results/*.jsonl`. Band of 65 ticks unless noted. Times in ms.\n\n",
    );
    if let Some(m) = reference
        .values()
        .chain(tee.values())
        .next()
        .and_then(|v| v.get("machine"))
    {
        let _ = writeln!(md, "Machine: `{m}`\n");
    }

    // Latency by backend and batch size.
    let mut ns: Vec<u64> = reference
        .keys()
        .chain(tee.keys())
        .chain(mpc.keys())
        .chain(zk.keys())
        .copied()
        .collect();
    ns.sort_unstable();
    ns.dedup();
    md.push_str("## Execution latency by batch size\n\n| n | ref p50 | ref p99 | TEE p50 | TEE p95 | TEE p99 | TEE orders/s | MPC LAN p50 | MPC WAN p50 | TEE+ZK prove p50 |\n|---|---|---|---|---|---|---|---|---|---|\n");
    let mut tex = String::from(
        "\\begin{tabular}{rrrrrrrr}\n\\toprule\n$n$ & \\multicolumn{2}{c}{Reference} & \\multicolumn{2}{c}{TEE (sim.)} & \\multicolumn{2}{c}{MPC online (model)} & TEE+ZK \\\\\n & p50 & p99 & p50 & p99 & LAN & WAN & prove \\\\\n\\midrule\n",
    );
    for n in &ns {
        let r = reference.get(n);
        let t = tee.get(n);
        let m = mpc.get(n);
        let z = zk.get(n);
        let g = |o: Option<&Value>, k: &str| o.map_or(f64::NAN, |v| f(v, k));
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            fmt_n(*n),
            fmt_ms(g(r, "p50_ms")),
            fmt_ms(g(r, "p99_ms")),
            fmt_ms(g(t, "p50_ms")),
            fmt_ms(g(t, "p95_ms")),
            fmt_ms(g(t, "p99_ms")),
            t.map_or("--".into(), |v| format!(
                "{:.0}",
                f(v, "throughput_orders_per_s")
            )),
            fmt_ms(g(m, "online_lan_p50_ms")),
            fmt_ms(g(m, "online_wan_p50_ms")),
            fmt_ms(g(z, "prove_p50_ms")),
        );
        let _ = writeln!(
            tex,
            "{} & {} & {} & {} & {} & {} & {} & {} \\\\",
            fmt_n(*n),
            fmt_ms(g(r, "p50_ms")),
            fmt_ms(g(r, "p99_ms")),
            fmt_ms(g(t, "p50_ms")),
            fmt_ms(g(t, "p99_ms")),
            fmt_ms(g(m, "online_lan_p50_ms")),
            fmt_ms(g(m, "online_wan_p50_ms")),
            fmt_ms(g(z, "prove_p50_ms")),
        );
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    std::fs::write(tables.join("latency.tex"), tex)?;

    // TEE stage breakdown.
    md.push_str("\n## TEE stage breakdown (mean ms)\n\n| n | check-header | attest+release | open | order | validate | match | settle | CPU ms/rep | peak heap MB |\n|---|---|---|---|---|---|---|---|---|---|\n");
    for (n, v) in &tee {
        let s = v.get("stages_mean_ms").cloned().unwrap_or_default();
        let st = |k: &str| fmt_ms(s.get(k).and_then(Value::as_f64).unwrap_or(f64::NAN));
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {:.0} |",
            fmt_n(*n),
            st("check-header"),
            st("attest+release"),
            st("open"),
            st("order"),
            st("validate"),
            st("match"),
            st("settle"),
            fmt_ms(f(v, "cpu_ms_per_rep")),
            u(v, "peak_heap_bytes") as f64 / 1_048_576.0
        );
    }

    // MPC costs.
    md.push_str("\n## MPC online cost (3 parties, log-depth comparisons, MACs)\n\n| n | rounds | MB/party | multiplications | comparisons | triples | compute/party | LAN | WAN | peak heap MB |\n|---|---|---|---|---|---|---|---|---|---|\n");
    let mut tex = String::from(
        "\\begin{tabular}{rrrrrrrr}\n\\toprule\n$n$ & rounds & MB/party & mult. & comp. & compute/party & LAN & WAN \\\\\n\\midrule\n",
    );
    for (n, v) in &mpc {
        let tr = v
            .get("preprocessing")
            .and_then(|p| p.get("triples"))
            .and_then(Value::as_u64)
            .unwrap_or(0);
        let mb = u(v, "bytes_per_party") as f64 / 1e6;
        let _ = writeln!(
            md,
            "| {} | {} | {:.1} | {} | {} | {} | {} | {} | {} | {:.0} |",
            fmt_n(*n),
            u(v, "rounds"),
            mb,
            u(v, "multiplications"),
            u(v, "comparisons"),
            tr,
            fmt_ms(f(v, "per_party_compute_p50_ms")),
            fmt_ms(f(v, "online_lan_p50_ms")),
            fmt_ms(f(v, "online_wan_p50_ms")),
            u(v, "peak_heap_bytes") as f64 / 1_048_576.0
        );
        let _ = writeln!(
            tex,
            "{} & {} & {:.1} & {:.2}M & {} & {} & {} & {} \\\\",
            fmt_n(*n),
            u(v, "rounds"),
            mb,
            u(v, "multiplications") as f64 / 1e6,
            u(v, "comparisons"),
            fmt_ms(f(v, "per_party_compute_p50_ms")),
            fmt_ms(f(v, "online_lan_p50_ms")),
            fmt_ms(f(v, "online_wan_p50_ms"))
        );
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    std::fs::write(tables.join("mpc.tex"), tex)?;

    md.push_str("\n## MPC variants at n = 1k\n\n| parties | circuit | MACs | band ticks | rounds | MB/party | comparisons | compute/party | LAN | WAN |\n|---|---|---|---|---|---|---|---|---|---|\n");
    let mut tex = String::from(
        "\\begin{tabular}{rlcrrrrrr}\n\\toprule\nparties & circuit & MACs & $K$ & rounds & MB/party & compute/party & LAN & WAN \\\\\n\\midrule\n",
    );
    // Both plans run some variants. Keep the latest record per configuration.
    let mut variants: Vec<(u64, &str, bool, u64, &Value)> = Vec::new();
    for v in mpc_all.iter().filter(|v| u(v, "n") == 1_000) {
        let circuit = v.get("circuit").and_then(Value::as_str).unwrap_or("?");
        let auth = v
            .get("authenticated")
            .and_then(Value::as_bool)
            .unwrap_or(true);
        let key = (u(v, "parties"), circuit, auth, u(v, "band_ticks"));
        match variants
            .iter_mut()
            .find(|(p, c, a, k, _)| (*p, *c, *a, *k) == key)
        {
            Some(slot) => slot.4 = v,
            None => variants.push((key.0, key.1, key.2, key.3, v)),
        }
    }
    for &(_, circuit, auth, _, v) in &variants {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {:.1} | {} | {} | {} | {} |",
            u(v, "parties"),
            circuit,
            if auth { "yes" } else { "no" },
            u(v, "band_ticks"),
            u(v, "rounds"),
            u(v, "bytes_per_party") as f64 / 1e6,
            u(v, "comparisons"),
            fmt_ms(f(v, "per_party_compute_p50_ms")),
            fmt_ms(f(v, "online_lan_p50_ms")),
            fmt_ms(f(v, "online_wan_p50_ms"))
        );
        let _ = writeln!(
            tex,
            "{} & {} & {} & {} & {} & {:.1} & {} & {} & {} \\\\",
            u(v, "parties"),
            circuit,
            if auth { "yes" } else { "no" },
            u(v, "band_ticks"),
            u(v, "rounds"),
            u(v, "bytes_per_party") as f64 / 1e6,
            fmt_ms(f(v, "per_party_compute_p50_ms")),
            fmt_ms(f(v, "online_lan_p50_ms")),
            fmt_ms(f(v, "online_wan_p50_ms"))
        );
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    std::fs::write(tables.join("mpc_variants.tex"), tex)?;

    // ZK.
    md.push_str("\n## Groth16 (BN254), one proof per batch\n\n| n | band ticks | constraints | setup | prove p50 | verify p50 | proof B | proving key MB |\n|---|---|---|---|---|---|---|---|\n");
    let mut tex = String::from(
        "\\begin{tabular}{rrrrrrr}\n\\toprule\n$n$ & $K$ & constraints & setup & prove & verify & pk (MB) \\\\\n\\midrule\n",
    );
    let mut zk_rows: BTreeMap<(std::cmp::Reverse<u64>, u64), Value> = BTreeMap::new();
    for v in load(dir, "zk") {
        zk_rows.insert((std::cmp::Reverse(u(&v, "band_ticks")), u(&v, "n")), v);
    }
    for v in zk_rows.into_values() {
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} | {} | {:.1} |",
            fmt_n(u(&v, "n")),
            u(&v, "band_ticks"),
            u(&v, "constraints"),
            fmt_ms(f(&v, "setup_ms")),
            fmt_ms(f(&v, "prove_p50_ms")),
            fmt_ms(f(&v, "verify_p50_ms")),
            u(&v, "proof_bytes"),
            u(&v, "proving_key_bytes") as f64 / 1e6
        );
        let _ = writeln!(
            tex,
            "{} & {} & {:.2}M & {} & {} & {} & {:.0} \\\\",
            fmt_n(u(&v, "n")),
            u(&v, "band_ticks"),
            u(&v, "constraints") as f64 / 1e6,
            fmt_ms(f(&v, "setup_ms")),
            fmt_ms(f(&v, "prove_p50_ms")),
            fmt_ms(f(&v, "verify_p50_ms")),
            u(&v, "proving_key_bytes") as f64 / 1e6
        );
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    std::fs::write(tables.join("zk.tex"), tex)?;

    // H4: band encoding vs sort.
    md.push_str("\n## H4: secure comparisons, band-encoded auction vs. sorting the keys alone\n\n| n | auction comparisons | auction LAN | bitonic sort comparisons | sort LAN | ratio |\n|---|---|---|---|---|---|\n");
    let mut tex = String::from(
        "\\begin{tabular}{rrrrrr}\n\\toprule\n$n$ & auction comp. & auction LAN & sort comp. & sort LAN & sort/auction \\\\\n\\midrule\n",
    );
    for (n, s) in &sort {
        let a = mpc_all
            .iter()
            .filter(|v| is_default_mpc(v))
            .find(|v| u(v, "n") == *n);
        let ac = a.map_or(0, |v| u(v, "comparisons"));
        let sc = u(s, "comparisons");
        let ratio = if ac > 0 {
            format!("{:.2}", sc as f64 / ac as f64)
        } else {
            "--".into()
        };
        let alan = a.map_or(f64::NAN, |v| f(v, "online_lan_p50_ms"));
        let _ = writeln!(
            md,
            "| {} | {} | {} | {} | {} | {} |",
            fmt_n(*n),
            if ac > 0 { ac.to_string() } else { "--".into() },
            fmt_ms(alan),
            sc,
            fmt_ms(f(s, "online_lan_ms")),
            ratio
        );
        let _ = writeln!(
            tex,
            "{} & {} & {} & {} & {} & {} \\\\",
            fmt_n(*n),
            if ac > 0 { ac.to_string() } else { "--".into() },
            fmt_ms(alan),
            sc,
            fmt_ms(f(s, "online_lan_ms")),
            ratio
        );
    }
    tex.push_str("\\bottomrule\n\\end{tabular}\n");
    std::fs::write(tables.join("sort.tex"), tex)?;

    if let Some(s) = sizes.last() {
        let _ = writeln!(
            md,
            "\n## Message sizes\n\nsealed envelope {} B, masked intent {} B (K = {}), batch header {} B\n",
            u(s, "sealed_envelope_bytes"),
            u(s, "masked_intent_bytes"),
            u(s, "band_ticks"),
            u(s, "batch_header_bytes")
        );
    }

    if !settlement.is_empty() {
        md.push_str("\n## On-chain settlement (LiteSVM, compute units)\n\n| deltas | post receipt | verify / delta | apply / delta | close | largest tx | total | transactions |\n|---|---|---|---|---|---|---|---|\n");
        let mut tex = String::from(
            "\\begin{tabular}{rrrrrrrr}\n\\toprule\ndeltas & post & verify/delta & apply/delta & close & max tx & total & txs \\\\\n\\midrule\n",
        );
        for v in &settlement {
            let cells = [
                u(v, "deltas").to_string(),
                u(v, "post_cu").to_string(),
                u(v, "verify_cu_per_delta").to_string(),
                u(v, "apply_cu_per_delta").to_string(),
                u(v, "close_cu").to_string(),
                u(v, "max_tx_cu").to_string(),
                format!("{:.2}M", u(v, "total_cu") as f64 / 1e6),
                u(v, "transactions").to_string(),
            ];
            let _ = writeln!(md, "| {} |", cells.join(" | "));
            let _ = writeln!(tex, "{} \\\\", cells.join(" & "));
        }
        tex.push_str("\\bottomrule\n\\end{tabular}\n");
        std::fs::write(tables.join("settlement.tex"), tex)?;
    }

    std::fs::write(dir.join("summary.md"), md)?;
    eprintln!(
        "wrote {} and tables in {}",
        dir.join("summary.md").display(),
        tables.display()
    );
    Ok(())
}
