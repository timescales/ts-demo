// Writes etc/sdk.api.d.ts: the public declarations of every subpath export,
// subpaths and names sorted, comments removed and formatted with Prettier.
// Later packages regenerate it and `git diff --exit-code` must stay clean, so
// the frozen SDK surface cannot drift unnoticed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import ts from 'typescript';

const pkgDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(pkgDir, 'etc', 'sdk.api.d.ts');
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const VIRTUAL = join(pkgDir, '.api-report');

function fail(message) {
  console.error(`api-report: ${message}`);
  process.exit(1);
}

const configPath = join(pkgDir, 'tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if (config.error) fail(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, pkgDir);
const options = {
  ...parsed.options,
  noEmit: false,
  declaration: true,
  emitDeclarationOnly: true,
  declarationMap: false,
  sourceMap: false,
  outDir: VIRTUAL,
};

// 1. Emit the declarations in memory.
const emitted = new Map();
const program = ts.createProgram(parsed.fileNames, options);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length > 0) {
  fail(ts.formatDiagnosticsWithColorAndContext(diagnostics, ts.createCompilerHost(options)));
}
const emit = program.emit(
  undefined,
  (file, text) => emitted.set(resolve(file), text),
  undefined,
  true,
);
if (emit.diagnostics.length > 0) fail('declaration emit failed');

// 2. Type-check the emitted declarations and walk each entry's exports.
const host = ts.createCompilerHost(options);
const readFile = host.readFile.bind(host);
const fileExists = host.fileExists.bind(host);
host.readFile = (f) => emitted.get(resolve(f)) ?? readFile(f);
host.fileExists = (f) => emitted.has(resolve(f)) || fileExists(f);
const directoryExists = host.directoryExists?.bind(host) ?? ts.sys.directoryExists;
host.directoryExists = (d) => resolve(d).startsWith(VIRTUAL) || directoryExists(d);

const entries = Object.entries(pkg.exports)
  .map(([subpath, target]) => {
    const source = resolve(pkgDir, target.source);
    const dts = join(VIRTUAL, relative(join(pkgDir, 'src'), source)).replace(/\.ts$/, '.d.ts');
    return { name: subpath === '.' ? pkg.name : `${pkg.name}/${subpath.slice(2)}`, dts };
  })
  .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

const declProgram = ts.createProgram(
  entries.map((e) => e.dts),
  { ...options, noEmit: true, emitDeclarationOnly: false, declaration: false },
  host,
);
const checker = declProgram.getTypeChecker();
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

function statementOf(decl) {
  return ts.isVariableDeclaration(decl) ? decl.parent.parent : decl;
}

const sections = [];
for (const entry of entries) {
  const sf = declProgram.getSourceFile(entry.dts);
  if (sf === undefined) fail(`no declarations for ${entry.name}`);
  const moduleSymbol = checker.getSymbolAtLocation(sf);
  if (moduleSymbol === undefined) fail(`${entry.name} has no exports`);
  const lines = [`// ${entry.name}`];
  const exports = checker
    .getExportsOfModule(moduleSymbol)
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const sym of exports) {
    const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
    const decls = target.declarations ?? [];
    if (decls.length === 0) fail(`${entry.name}: ${sym.name} has no declaration`);
    if (target.name !== sym.name) lines.push(`// ${sym.name} is ${target.name}`);
    const seen = new Set();
    for (const d of decls) {
      const stmt = statementOf(d);
      if (seen.has(stmt)) continue;
      seen.add(stmt);
      lines.push(printer.printNode(ts.EmitHint.Unspecified, stmt, stmt.getSourceFile()));
    }
  }
  sections.push(lines.join('\n'));
}

const header = [
  '// The public declarations of @timescales/sdk, one section per subpath export.',
  '// Generated by `npm run api-report` (etc/api-report.mjs); do not edit.',
  '',
].join('\n');
const prettierConfig = (await prettier.resolveConfig(outFile)) ?? {};
const text = await prettier.format(`${header}\n${sections.join('\n\n')}\n`, {
  ...prettierConfig,
  parser: 'typescript',
});
writeFileSync(outFile, text);
console.log(
  `api-report: wrote ${relative(process.cwd(), outFile)} (${entries.length} entry points)`,
);
